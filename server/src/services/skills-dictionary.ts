/** Bare name never matches for these; only the aliases do. See the file comment. */
const AMBIGUOUS = new Set(["go", "r", "swift", "excel", "spark", "express", "unity", "julia", "dart"]);

const esc = (s: string) => s.replace(/[.*+?^${}()|[\]\\/]/g, "\\$&");

// Boundary that survives punctuation terms: not glued to a letter/digit before, and not followed by a letter, digit,
// "+" or "#" after ("react" must not match "reactive", "c" must not match inside "c++").
const MATCHERS = Object.entries(SKILLS).map(([term, aliases]) => {
  const names = [...(AMBIGUOUS.has(term) ? [] : [term]), ...aliases].map(esc);
  return { term, re: new RegExp(`(?<![a-z0-9_.])(?:${names.join("|")})(?![a-z0-9_+#])`, "i") };
});

/** Canonical skill terms found in the text, deduped, in first-seen order. Unrecognized terms emit nothing. */
export function findSkills(text: string): string[] {
  const hits: { term: string; at: number }[] = [];
  for (const { term, re } of MATCHERS) {
    const at = text.search(re);
    if (at >= 0) hits.push({ term, at });
  }
  return hits.sort((a, b) => a.at - b.at).map((h) => h.term);
}
